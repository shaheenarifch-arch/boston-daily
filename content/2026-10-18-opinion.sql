But there is an important distinction between price increases caused by ordinary market forces and those materially influenced by government decisions, including decisions surrounding an armed conflict that policymakers have the power to pursue, limit or work to bring to an end.

My position is straightforward: if government chooses a course of action that materially increases energy costs for its citizens, government should also accept responsibility for helping households absorb that extraordinary cost.

## A targeted Fuel Price Relief Credit

Citizens should not receive unlimited reimbursement for every gallon of gasoline. Instead, Congress should consider a temporary, targeted Fuel Price Relief Credit.

The principle would be simple:

> **Extraordinary qualifying price increase × standardized essential household fuel consumption = potential relief**

If policymakers establish a benchmark and gasoline rises substantially above it because of qualifying extraordinary circumstances, eligible households could receive compensation for part of that difference.

The relief should be:

- Targeted toward households that genuinely need assistance
- Capped at a reasonable level of essential fuel consumption
- Temporary rather than permanent
- Transparent about its cost to taxpayers
- Reduced or ended when fuel prices normalize
- Subject to congressional authorization and appropriate oversight

The federal tax system could potentially provide a mechanism for distributing such relief if lawmakers establish the necessary program and authority.

## Address the cause, not only the cost

But financial assistance addresses only the consequence. Government should also address the cause.

If an armed conflict is contributing to economic hardship and there is a realistic opportunity for government to help bring that conflict to an end, political leaders have a responsibility to pursue diplomacy and peace seriously.

War carries consequences far beyond the battlefield. Geopolitical instability can affect energy markets, transportation costs, food prices, businesses and household budgets.

Citizens therefore have every right to ask difficult questions:

- Was the policy necessary?
- Are alternatives being pursued?
- Is every reasonable opportunity for diplomacy being considered?
- Is there a credible path toward peace?
- And if government decisions impose extraordinary costs on ordinary people, who should bear those costs?

## Who should pay

My answer to the last question is clear: government should not make consequential decisions and then transfer the entire economic burden to its citizens.

When public policy imposes extraordinary costs on everyday necessities, government should be prepared to share that burden while continuing to pursue policies that reduce the underlying problem.

Peace should always be pursued where realistically possible. Until extraordinary costs subside, working families should not be left to face those consequences alone.

Government makes the policy decisions. Ordinary families should not be handed the entire bill.

