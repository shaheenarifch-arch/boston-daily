## How Boston Daily reports the news

Boston Daily is open about how it works. Its [editorial standards page](https://bostondaily.us/standards) sets out five commitments that matter most for readers.

### AI helps, editors decide

The site uses AI tools to spot news, gather public records and sources, and write first drafts. Those tools do not publish anything on their own. An editor checks facts, names, quotes and sources and approves every news story before it goes live. News stories carry a short AI-use note under the byline so readers know how the story was made. Opinion columns are written and signed by their named authors.

### Sourcing and copyright

Boston Daily reports from primary sources, official records, licensed wire services, permitted press releases and its own reporting. It does not copy or closely rewrite other outlets'' articles. When it learns about a story from another outlet, it uses that coverage only as a lead and then reports the story from original sources. Images run only when the site holds the rights to use them, and every story lists its public sources at the end.

### Human approval for sensitive stories

No news story is published without an editor''s approval. Stories about US politics and health always get editor review, sensitive or unverified material is never published automatically, and election results come only from official or licensed results feeds. The US Politics section repeats this promise at the top of its page.

### Updates and corrections

When a story changes because of new information, it is marked Updated with a note explaining what changed. When the site fixes an error, the story is marked Corrected with an explanation, and earlier versions are kept. All corrections are listed on the [corrections page](https://bostondaily.us/corrections). To report an error, email editor@bostondaily.us with a link to the story.

### Labels you can trust

Opinion pieces carry an Opinion label and live in the Opinion section, and analysis is labeled as analysis. Anything commercial is labeled too, as explained in the next section.

## How Boston Daily makes money

Boston Daily is free to read. It pays for itself through affiliate links, advertising, sponsored content and businesses in the GetServices.ai network. The standards page lays out the rules that keep that money away from the news:

- Commercial content is always labeled **Affiliate**, **Sponsored**, **Partner Content**, **Paid Listing** or **Advertisement**.
- It appears in separate modules and never in news story lists.
- Partner guides are not written by the newsroom and never carry a newsroom byline.
- Advertisers and partners cannot buy, edit, approve or suppress coverage.
- There is no commercial content on US Politics pages or beside sensitive stories.

Every page also ends with a short disclosure that some links are partner links and may earn a commission, with a link to [how the site labels commercial content](https://bostondaily.us/standards#commercial).

### Ownership, stated plainly

The businesses in the Recommended Businesses section and the courses from RealSkillSet are part of the same GetServices.ai network that owns Boston Daily. The site says so wherever they appear, so readers can weigh those recommendations accordingly.

