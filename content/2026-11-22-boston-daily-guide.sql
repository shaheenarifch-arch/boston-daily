### The house rules for advertisers

Boston Daily''s "How advertising works here" section is short and firm:

- Every paid item is labeled Advertisement, Sponsored, Paid Listing or Presented by.
- Advertisers never buy, edit, approve or suppress news coverage, and ads never appear in news story lists, Top Stories or the lead slot.
- There are no ads or sponsors on US Politics pages, and no political advertising.
- Ads do not run beside tragedies, disasters, crime or other sensitive stories.
- Every advertiser, creative and landing page is reviewed before anything goes live, and you must own the rights to your creative.
- The site does not accept ads for illegal products, weapons, adult content, counterfeit goods, unapproved health or financial claims, or unreviewed crypto schemes.

If your product falls into one of those categories, it is better to know before you plan the campaign.

### Sponsored content versus guest posts

Sponsored content and guest posts are two different things on Boston Daily, and the site keeps them apart. A sponsored article is paid for by an advertiser, labeled Sponsored and kept out of the news. A guest post is free, unpaid and chosen on its merits by the editor. If you want a guaranteed, paid placement, ask about sponsored content. If you want to share expertise or an argument, pitch a guest post.

## Writing for Boston Daily

![The Write for Boston Daily page](/img/guides/boston-daily-guide-write-for-us.jpg "The Write for Boston Daily page sets out the guest post guidelines and a quick checklist. Screenshot of bostondaily.us/write-for-us, Nov. 21, 2026.")

Boston Daily publishes guest columns and analysis in its Opinion section. The [Write for Boston Daily page](https://bostondaily.us/write-for-us) says guest posts are free to submit and that every piece is read and approved by the editor before it is published.

### Guest post guidelines

Here is what the editor looks for, in the site''s own terms:

- **Original and exclusive:** not published anywhere else, including your own blog, LinkedIn or Medium, and not reposted elsewhere for 30 days after it runs.
- **Length:** 800 to 1,500 words, with a clear argument and your own perspective or expertise.
- **Facts:** figures and quotes backed up with sources. Opinions are welcome; made-up facts are not.
- **Written by you:** you may use tools to check grammar, but the ideas and writing must be yours. Mass-produced AI text is declined.
- **Links:** up to three helpful links in the article and one link in your bio. Guest links are marked nofollow, as [Google recommends](https://developers.google.com/search/docs/crawling-indexing/qualify-outbound-links).
- **A real photo:** one real photo you hold the rights to, which has not been used elsewhere on the site.
- **Free and independent:** the site never charges to publish a guest post and never accepts payment for one.
- **Not accepted:** gambling, adult content, payday loans, crypto promotion, unproven health claims, personal attacks and anything that breaks the editorial standards.

The editor may edit for length, clarity, accuracy and style, and decides the headline and the publication date. Published guest posts carry a byline in the form "Your Name | Guest Contributor".

### How to submit and track a guest post

1. Read the guidelines on the Write for Boston Daily page.
2. Press **Submit a guest post** and fill in the form: the section, headline, a short summary, your article, a link to your photo with its credit, your sources, and your name, email, short bio and website.
3. Keep the reference number in your confirmation email.
4. Expect a reply within about five business days.
5. Check progress at any time on the [submission status page](https://bostondaily.us/guest-post/status).

